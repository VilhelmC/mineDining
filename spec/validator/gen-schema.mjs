// Writes src/schema.ts from ../schema/recipe.schema.json so the validator runs in browsers (no fs at runtime).
import { readFileSync, writeFileSync } from "node:fs";
const schema = readFileSync(new URL("../schema/recipe.schema.json", import.meta.url), "utf-8");
const body = JSON.stringify(JSON.parse(schema), null, "\t");
writeFileSync(
	new URL("./src/schema.ts", import.meta.url),
	`/* eslint-disable */\n// GENERATED by gen-schema.mjs from spec/schema/recipe.schema.json. Do not edit.\nexport const schema = ${body};\n`,
);
